"""Puertos (interfaces) que la capa de aplicación necesita. La infraestructura los implementa."""
from typing import Protocol


class PedidoRepositorio(Protocol):
    def obtener(self, id): ...
    def guardar(self, pedido): ...
    def listar(self, estado=None): ...


class PlatilloRepositorio(Protocol):
    def obtener(self, id): ...
    def obtener_varios(self, ids): ...
    def listar(self): ...
    def guardar(self, platillo): ...


class ActorRepositorio(Protocol):
    def obtener(self, id): ...
    def listar(self): ...
    def guardar(self, actor): ...


class AuditoriaRepositorio(Protocol):
    """Solo agrega y consulta: no existe forma de actualizar o borrar (ADR-005)."""

    def agregar(self, registro): ...
    def listar(self, pedido_id=None, accion=None): ...


class UnitOfWork(Protocol):
    pedidos: PedidoRepositorio
    platillos: PlatilloRepositorio
    actores: ActorRepositorio
    auditoria: AuditoriaRepositorio

    def __enter__(self): ...
    def __exit__(self, tipo, error, traza): ...
    def commit(self): ...
